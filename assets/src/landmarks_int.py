    RRAD = 7.6
    N = 48  # chunky, PS2-era facets (and a smaller file)
    VOM = [math.radians(a) for a in (28, 62, 118, 152, 208, 242, 298, 332)]
    vw = lambda th: 1.6 / max(1.0, rr_ray(th, A_, B_, RR, 7.0))  # half angle of a 3.2 m tunnel
    ths = sorted(set(round(t % (2 * math.pi), 6) for t in [2 * math.pi * i / N for i in range(N)] + [v - vw(v) for v in VOM] + [v + vw(v) for v in VOM]))
    angd = lambda a, b: abs(((a - b + math.pi) % (2 * math.pi)) - math.pi)
    in_vom = lambda th: any(angd(th, v) < vw(v) - 1e-6 for v in VOM)
    pt = lambda th, r: (cx + math.cos(th) * r, cy + math.sin(th) * r)
    r_rr = lambda th, t: rr_ray(th, A_, B_, RR, t)
    in_rot = lambda p: math.hypot(p[0] - rx_, p[1] - ry_) < RRAD - 0.3

    def r_out(th):  # the concourse's outer wall: the building wall, closed off at the west (back-of-house) end
        return min(poly_ray(P, cx, cy, th) - 0.4, r_rr(th, 24.0))
    for i in range(len(P)):  # the back-of-house block past the concourse's west end stays shut (its outer walls)
        a, b = P[i], P[(i + 1) % len(P)]
        if rr_sdf((a[0] + b[0]) / 2 - cx, (a[1] + b[1]) / 2 - cy, A_, B_, RR) > 24.5:
            Rm.wall(a, b, 24, 1.0, 0, out=(cx, cy))
