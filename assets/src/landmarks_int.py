# ---------------------------------------------------------------- shared: walls round a walkable outline, shop fronts
def outline(K, Rm, pts, kinds, z1, wallc, cb=None, doors=None, th=0.8, h=14):
    """inward walls round a polygon of Blender points; kinds[i] names edge i (pts[i] -> pts[i+1]); cb(i, kind, a, b, inward)
    dresses each edge; doors {i: (u0, u1[, h]) or a list of them, 'h': default height} leave gaps (metres from pts[i])"""
    n = len(pts)
    area = sum(pts[i][0] * pts[(i + 1) % n][1] - pts[(i + 1) % n][0] * pts[i][1] for i in range(n))
    sgn = 1 if area > 0 else -1
    for i in range(n):
        a, b = pts[i], pts[(i + 1) % n]
        dx, dy = b[0] - a[0], b[1] - a[1]
        Ln = math.hypot(dx, dy)
        if Ln < 0.01:
            continue
        inw = (-dy / Ln * sgn, dx / Ln * sgn)
        mid = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
        tw = (mid[0] + inw[0] * 5, mid[1] + inw[1] * 5)
        outp = (mid[0] - inw[0] * 5, mid[1] - inw[1] * 5)
        at = lambda u: (a[0] + dx / Ln * u, a[1] + dy / Ln * u)
        gaps = (doors or {}).get(i, [])
        gaps = [gaps] if isinstance(gaps, tuple) else gaps
        spans, t0 = [], 0.0
        for g in sorted(gaps):
            spans.append((t0, g[0]))
            gh = g[2] if len(g) > 2 else doors.get('h', 3.4)
            if gh < z1:
                vwall(K, at(g[0]), at(g[1]), gh, z1, wallc, tw)
            t0 = g[1]
        spans.append((t0, Ln))
        for s0, s1 in spans:
            if s1 - s0 > 0.01:
                vwall(K, at(s0), at(s1), 0, z1, wallc, tw)
                Rm.wall(at(s0), at(s1), h, th, 0, out=outp)
        if cb:
            cb(i, kinds[i], a, b, inw)


