# Quad Cities interiors (roadmap 5), loaded at the end of landmarks.py (same globals: Kit, finish, lin, B, ...).
# Walk-in interiors for the Moline / Rock Island / Arsenal / airport / NorthPark / Black Hawk landmarks: <name>_int.glb
# at the exterior's anchor (src/landmarks.js puts it on the same ground height). Besides the GLB, each builder writes
# its collision walls, the townspeople standing in it and the counters you can use (E) to src/landmark-rooms.js, so the
# geometry and the game data never drift apart. References: docs/landmarks-references.md (Interiors, roadmap 5).
import json as _json


class Rooms:
    """collects game data for one interior: walls (Blender segments -> game solid boxes), crowd, spots"""

    def __init__(self, anchor):
        self.ax, self.az = anchor
        self.solid, self.crowd, self.spots, self.halls = [], [], [], []

    def g(self, p):
        return (p[0] + self.ax, self.az - p[1])

    def wall(self, a, b, h, th=0.8, up=0.0, out=None):
        """a wall box along Blender segment a->b, h tall from `up` above the floor; out: a Blender point on the side
        the box is pushed to (so its inner face sits on the segment); without it the box is centred on the segment"""
        A, Bq = self.g(a), self.g(b)
        dx, dz = Bq[0] - A[0], Bq[1] - A[1]
        Ln = math.hypot(dx, dz)
        if Ln < 0.05:
            return
        cx, cz = (A[0] + Bq[0]) / 2, (A[1] + Bq[1]) / 2
        if out is not None:
            O = self.g(out)
            nx, nz = -dz / Ln, dx / Ln
            if (O[0] - cx) * nx + (O[1] - cz) * nz < 0:
                nx, nz = -nx, -nz
            cx, cz = cx + nx * th / 2, cz + nz * th / 2
        self.solid.append([round(cx, 2), round(cz, 2), round(Ln / 2 + 0.05, 2), round(th / 2, 2), round(h, 2), round(up, 2), round(math.atan2(-dz, dx), 4)])

    def block(self, x0, x1, y0, y1, h, up=0.0):
        """an axis-aligned Blender box as a solid"""
        A, Bq = self.g((x0, y0)), self.g((x1, y1))
        self.solid.append([round((A[0] + Bq[0]) / 2, 2), round((A[1] + Bq[1]) / 2, 2), round(abs(x1 - x0) / 2, 2), round(abs(y1 - y0) / 2, 2), round(h, 2), round(up, 2), 0])

    def person(self, p, face, pose, up=0.0, role='walk'):
        """someone at Blender point p looking at Blender point `face` (or with game heading `face`, radians)"""
        x, z = self.g(p)
        if isinstance(face, (tuple, list)):
            fx, fz = self.g(face)
            h = math.atan2(fx - x, fz - z)
        else:
            h = face
        self.crowd.append([round(x, 2), round(z, 2), round(h, 3), pose, round(up, 2), role])

    def hall(self, name, c, w, d, axis=(1.0, 0.0), up=0.02, ly=4.0, light=None):
        """a room for interiors.js: centre c and its own x axis `axis`, both in Blender coords; w along the axis"""
        x, z = self.g(c)
        h = dict(name=name, x=round(x, 2), z=round(z, 2), w=round(w, 2), d=round(d, 2), rot=round(math.atan2(axis[1], axis[0]), 4), up=up, ly=ly)
        if light:
            h['light'] = light
        self.halls.append(h)

    def spot(self, p, r, act, title, menu=None):
        x, z = self.g(p)
        self.spots.append([round(x, 2), round(z, 2), r, act, title] + ([menu] if menu else []))

    def save(self, name):
        p = ROOT + 'src/landmark-rooms.js'
        J = {}
        if os.path.exists(p):
            J = _json.loads(open(p).read().split('export const ROOMS = ', 1)[1].rstrip().rstrip(';'))
        J[name] = dict(solid=self.solid, crowd=self.crowd, spots=self.spots, halls=self.halls)
        head = ('// Generated by assets/src/landmarks_int.py (the roadmap-5 *_int builders): rebuild the interior instead of editing.\n'
                '// Per interior: solid walls [x, z, half x, half z, height, base above the ground at the anchor, heading], the crowd\n'
                '// [x, z, heading, pose, floor height, role] and counters [x, z, radius, act, title, menu] (venues.js).\n'
                'export const ROOMS = ')
        body = ',\n'.join('  %s: %s' % (_json.dumps(k), _json.dumps(v, separators=(',', ':'))) for k, v in sorted(J.items()))
        open(p, 'w').write(head + '{\n' + body + '\n};\n')
        return len(self.solid)


def rr_sdf(px, py, a, b, r):
    qx, qy = abs(px) - (a - r), abs(py) - (b - r)
    return math.hypot(max(qx, 0), max(qy, 0)) + min(max(qx, qy), 0) - r


def rr_ray(th, a, b, r, t):
    """distance from the centre along angle th to the outline of the rounded rect (half a x b, corner r) grown by t"""
    lo, hi = 0.0, a + b + abs(t) + 10
    c, s = math.cos(th), math.sin(th)
    for _ in range(40):
        m = (lo + hi) / 2
        if rr_sdf(c * m, s * m, a, b, r) < t:
            lo = m
        else:
            hi = m
    return lo


def poly_ray(P, cx, cy, th):
    """distance from (cx, cy) along angle th to the nearest edge of polygon P"""
    dx, dy = math.cos(th), math.sin(th)
    best = 1e9
    for i in range(len(P)):
        (x1, y1), (x2, y2) = P[i], P[(i + 1) % len(P)]
        ex, ey = x2 - x1, y2 - y1
        den = dx * ey - dy * ex
        if abs(den) < 1e-9:
            continue
        t = ((x1 - cx) * ey - (y1 - cy) * ex) / den
        u = ((x1 - cx) * dy - (y1 - cy) * dx) / den
        if t > 0 and -1e-6 <= u <= 1 + 1e-6:
            best = min(best, t)
    return best


def in_poly(P, x, y):
    ins = False
    j = len(P) - 1
    for i in range(len(P)):
        if (P[i][1] > y) != (P[j][1] > y) and x < (P[j][0] - P[i][0]) * (y - P[i][1]) / (P[j][1] - P[i][1]) + P[i][0]:
            ins = not ins
        j = i
    return ins


def flat(K, pts, z, col, m=BODY, up=True):
    """a horizontal polygon at height z seen from above (up) or from below"""
    pts = [(p[0], p[1], z) for p in pts]
    a = sum((pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]) for i in range(len(pts)))
    if (a > 0) != up:
        pts = pts[::-1]
    K.face(pts, col, m)


def frect(K, x0, x1, y0, y1, z, col, m=BODY, up=True):
    flat(K, [(x0, y0), (x1, y0), (x1, y1), (x0, y1)], z, col, m, up)


def disc(K, cx, cy, r, z, col, m=BODY, seg=24, up=True, r0=0.0):
    """a flat disc (or a ring from r0) at height z"""
    if r0 > 0:
        for i in range(seg):
            a0, a1 = 2 * math.pi * i / seg, 2 * math.pi * (i + 1) / seg
            flat(K, [(cx + math.cos(a0) * r0, cy + math.sin(a0) * r0), (cx + math.cos(a1) * r0, cy + math.sin(a1) * r0), (cx + math.cos(a1) * r, cy + math.sin(a1) * r), (cx + math.cos(a0) * r, cy + math.sin(a0) * r)], z, col, m, up)
    else:
        flat(K, [(cx + math.cos(2 * math.pi * i / seg) * r, cy + math.sin(2 * math.pi * i / seg) * r) for i in range(seg)], z, col, m, up)


def vwall(K, a, b, z0, z1, col, toward, m=BODY):
    """vertical quad on segment a-b facing the point `toward`"""
    iface(K, [(a[0], a[1], z0), (b[0], b[1], z0), (b[0], b[1], z1), (a[0], a[1], z1)], (toward[0], toward[1], (z0 + z1) / 2), col, m)


def wframe(a, b, toward, z=0.0):
    """frame on the wall a-b seen from `toward`: d points at the viewer, h up from z, u along the wall running so that
    u x up = d (quads and letters then face the viewer; the ends may swap, so callers use it symmetrically)"""
    if (toward[0] - a[0]) * (b[1] - a[1]) - (toward[1] - a[1]) * (b[0] - a[0]) < 0:
        a, b = b, a
    dx, dy = b[0] - a[0], b[1] - a[1]
    Ln = math.hypot(dx, dy)
    ux, uy = dx / Ln, dy / Ln
    nx, ny = uy, -ux
    return (lambda u, h, d: (a[0] + ux * u + nx * d, a[1] + uy * u + ny * d, z + h)), Ln


def wtext(K, a, b, toward, s, u, h, size, col, m=BODY, d=0.03, z=0.0):
    """flat letters on a wall a-b, readable from the `toward` side, centred u along it"""
    L, Ln = wframe(a, b, toward, z)
    return K.text(s, L, u, h, d, size, col, m, 0.03, res=1, front=True)


def counter(K, Rm, a, b, z, depth, col, top, toward, h=1.05):
    """a service counter along a-b reaching `depth` away from `toward`, with its collision; returns its frame"""
    L, Ln = wframe(a, b, toward, z)
    F_ = lambda u, hh, d: L(u, hh, -d)
    K.obox(F_, 0, Ln, 0, h, 0, depth, col, BODY, ('h-',))
    K.obox(F_, -0.05, Ln + 0.05, h, h + 0.06, -0.08, depth, top, BODY, ('h-',))
    Rm.wall(F_(0, 0, depth / 2)[:2], F_(Ln, 0, depth / 2)[:2], 1.2, depth + 0.1)
    return F_


def bench(K, Rm, x, y, along_x, n=4, col=lin('#2f3a45'), z=0.0, solid=True):
    """a row of n connected seats (gate seating, waiting areas): 0.55 m a seat"""
    L = n * 0.55
    if along_x:
        K.box(x - L / 2, x + L / 2, y - 0.25, y + 0.25, z + 0.38, z + 0.46, col)
        K.box(x - L / 2, x + L / 2, y + 0.2, y + 0.27, z + 0.46, z + 0.9, col)
        K.box(x - L / 2, x + L / 2, y - 0.05, y + 0.05, z, z + 0.38, lin('#9aa0a6'))
        if solid:
            Rm.block(x - L / 2, x + L / 2, y - 0.3, y + 0.3, 0.9)
    else:
        K.box(x - 0.25, x + 0.25, y - L / 2, y + L / 2, z + 0.38, z + 0.46, col)
        K.box(x + 0.2, x + 0.27, y - L / 2, y + L / 2, z + 0.46, z + 0.9, col)
        K.box(x - 0.05, x + 0.05, y - L / 2, y + L / 2, z, z + 0.38, lin('#9aa0a6'))
        if solid:
            Rm.block(x - 0.3, x + 0.3, y - L / 2, y + L / 2, 0.9)


def plant(K, x, y, z=0.0, r=0.5, h=1.8):
    K.cyl(x, y, r, z, z + 0.6, lin('#8a8478'), BODY, 8)
    K.cyl(x, y, r * 1.3, z + 0.6, z + h, lin('#3f7a3a'), BODY, 6, r1=0.15)


def int_done(name, K, Rm, anchor, cam, target, render, lens=18):
    """finish an interior: GLB, game data, a preview from inside"""
    o = K.obj(name + '_int')
    res = finish(name + '_int', [o], anchor)
    res['walls'] = Rm.save(name)
    res['people'] = len(Rm.crowd)
    if render:
        res['png'] = [inside_shot(name + '_int', cam, target, lens)]
    return res


# ================================================================ VIBRANT ARENA AT THE MARK (Moline)
# 1201 River Dr (1993, Ellerbe Becket; Vibrant Arena since 2024): through the glass rotunda on the east into the ring
# concourse with its concession stands, then through the vomitory tunnels into the bowl: twelve rows of lower seats
# round the Quad City Storm's rink, the upper bowl hung over the concourse, suites under the roof and the centre-hung
# video board. (The real concourse is a level above the event floor; the game's floors are flat, so here the tunnels
# lead straight down to the boards.)
def arena_int(render=True):
    anchor = (4770.0, 1725.0)
    G = g2l(anchor)
    ring = [(4735.7, 1768.7), (4744.2, 1769.8), (4743.8, 1775.6), (4753.1, 1778.5), (4760.4, 1779.1), (4768.6, 1778.8), (4776.6, 1777.1), (4778.3, 1782.9),
            (4788.0, 1778.7), (4799.6, 1772.9), (4807.5, 1764.7), (4813.1, 1757.0), (4817.8, 1746.5), (4828.7, 1750.5), (4832.1, 1738.7), (4830.5, 1730.2),
            (4830.1, 1720.4), (4827.9, 1709.2), (4825.5, 1702.6), (4821.8, 1694.5), (4817.2, 1687.4), (4812.9, 1682.0), (4805.8, 1674.9), (4796.8, 1668.3),
            (4787.7, 1663.8), (4781.9, 1679.6), (4775.5, 1677.6), (4768.5, 1676.3), (4760.0, 1676.1), (4751.2, 1677.4), (4744.1, 1679.2), (4744.0, 1685.3),
            (4711.1, 1684.9), (4710.4, 1704.4), (4704.1, 1714.8), (4703.8, 1740.2), (4711.6, 1750.9), (4710.6, 1768.1)]
    P = ccw([G(*p) for p in ring])
    F = 0.5  # floor height above the anchor (the ground rises ~0.45 m across the footprint)
    K = Kit(711, ao=0)
    Rm = Rooms(anchor)
    cx, cy = G(4780, 1725)
    A_, B_, RR = 30.5, 13.0, 8.5  # the rink: 200 x 85 ft, 28 ft corners
    ice, red, blue, board, kick = lin('#d9e2e8'), lin('#c8102e'), lin('#1f4fa8'), lin('#f4f4f2'), lin('#e3c43a')
    conc, wallc, purple, char = lin('#8f8a82'), lin('#d9d9db'), lin('#5b2c83'), lin('#3a3a3c')
    seat_lo, seat_up, riser = lin('#3b2a5c'), lin('#2e2a46'), lin('#5a5a5e')
    rx_, ry_ = G(4832, 1740)
    RRAD = 7.6
    N = 48  # chunky, PS2-era facets (and a smaller file)
    VOM = [math.radians(a) for a in (28, 62, 118, 152, 208, 242, 298, 332)]
    vw = lambda th: 1.6 / max(1.0, rr_ray(th, A_, B_, RR, 7.0))  # half angle of a 3.2 m tunnel
    ths = sorted(set(round(t % (2 * math.pi), 6) for t in [2 * math.pi * i / N for i in range(N)] + [v - vw(v) for v in VOM] + [v + vw(v) for v in VOM]))
    angd = lambda a, b: abs(((a - b + math.pi) % (2 * math.pi)) - math.pi)
    in_vom = lambda th: any(angd(th, v) < vw(v) - 1e-6 for v in VOM)
    pt = lambda th, r: (cx + math.cos(th) * r, cy + math.sin(th) * r)
    r_rr = lambda th, t: rr_ray(th, A_, B_, RR, t)
    in_rot = lambda p: math.hypot(p[0] - rx_, p[1] - ry_) < RRAD - 0.3

    def r_out(th):  # the concourse's outer wall: the building wall, closed off at the west (back-of-house) end
        return min(poly_ray(P, cx, cy, th) - 0.4, r_rr(th, 24.0))
    for i in range(len(P)):  # the back-of-house block past the concourse's west end stays shut (its outer walls)
        a, b = P[i], P[(i + 1) % len(P)]
        if rr_sdf((a[0] + b[0]) / 2 - cx, (a[1] + b[1]) / 2 - cy, A_, B_, RR) > 24.5:
            Rm.wall(a, b, 24, 1.0, 0, out=(cx, cy))
            Rm.wall(a, b, 24, 1.0, 0, out=(2 * a[0] - cx, 2 * a[1] - cy))
    LB0, LB1, NL = 2.0, 12.2, 12  # lower bowl: from / to (offset from the boards), rows
    up_h = lambda j: F + 7.0 + 0.5 * j
    lo_h = lambda k: F + 1.25 + 0.4 * k
    M = len(ths)
    ctr = (cx, cy)
    for i in range(M):
        t0 = ths[i]
        t1 = ths[(i + 1) % M] + (2 * math.pi if i == M - 1 else 0)
        tm = (t0 + t1) / 2
        vom = in_vom(tm)
        ro0, ro1 = r_out(t0), r_out(t1)

        def q(r0a, r0b, r1a, r1b, z, col, up=True, m=BODY):
            flat(K, [pt(t0, r0a), pt(t1, r0b), pt(t1, r1b), pt(t0, r1a)], z, col, m, up)
        # floors: the walkway round the boards, the concourse ring; the concourse ceiling; the roof deck
        q(r_rr(t0, 0.15), r_rr(t1, 0.15), r_rr(t0, LB1), r_rr(t1, LB1), F, lin('#55555a'))
        q(r_rr(t0, LB1), r_rr(t1, LB1), ro0, ro1, F, conc if i % 2 else scale(conc, 0.95))
        q(r_rr(t0, LB1), r_rr(t1, LB1), ro0, ro1, F + 6.0, lin('#b9b9bc'), False)
        if i % 2 == 0:  # light panels down the middle of the concourse
            rm0, rm1 = (r_rr(t0, LB1) + ro0) / 2, (r_rr(t1, LB1) + ro1) / 2
            q(rm0 - 0.8, rm1 - 0.8, rm0 + 0.8, rm1 + 0.8, F + 5.97, lin('#fff4d8'), False, LIT)
        q(0, 0, ro0, ro1, F + 22.0, lin('#2c2f36'), False)
        # the outer wall seen from inside (open where the rotunda joins)
        a, b = pt(t0, ro0), pt(t1, ro1)
        rot = in_rot(a) and in_rot(b)
        if not rot:
            vwall(K, a, b, F, F + 4.2, wallc, ctr)
            vwall(K, a, b, F + 4.2, F + 4.8, purple, ctr)
            vwall(K, a, b, F + 4.8, F + 22, char, ctr)
            Rm.wall(a, b, 14, 0.8, 0, out=pt(tm, ro0 + 5))
        else:
            vwall(K, a, b, F + 11.0, F + 22, char, ctr)
        # the boards: yellow kick plate, white dasher, cap; two gates by the benches, one at the west end
        gate = any(angd(tm, g) < 0.03 for g in (math.radians(78), math.radians(102), math.radians(180)))
        b0, b1 = pt(t0, r_rr(t0, 0.0)), pt(t1, r_rr(t1, 0.0))
        o0, o1 = pt(t0, r_rr(t0, 0.15)), pt(t1, r_rr(t1, 0.15))
        if not gate:
            vwall(K, b0, b1, F, F + 0.25, kick, ctr)
            vwall(K, b0, b1, F + 0.25, F + 1.07, board, ctr)
            vwall(K, o0, o1, F, F + 1.07, board, pt(tm, 200))
            flat(K, [b0, b1, o1, o0], F + 1.07, lin('#e2e2e2'))
            Rm.wall(b0, b1, 1.1, 0.3)
            if i % 3 == 0:  # the glass posts
                K.box(b0[0] - 0.04, b0[0] + 0.04, b0[1] - 0.04, b0[1] + 0.04, F + 1.07, F + 2.9, lin('#c8ccd0'))
        # lower bowl: treads, risers, seat backs; the tunnels cut the first rows
        for k in range(NL):
            ra, rb = LB0 + (LB1 - LB0) * k / NL, LB0 + (LB1 - LB0) * (k + 1) / NL
            z = lo_h(k)
            if vom and z < F + 3.6:
                continue
            q(r_rr(t0, ra), r_rr(t1, ra), r_rr(t0, rb), r_rr(t1, rb), z, seat_lo if k % 2 == 0 else scale(seat_lo, 0.85))
            zp = F + 3.2 if vom and lo_h(k - 1) < F + 3.6 else (lo_h(k - 1) if k else F)
            vwall(K, pt(t0, r_rr(t0, ra)), pt(t1, r_rr(t1, ra)), zp, z, riser if k else purple, ctr)
            sb = rb - 0.18
            vwall(K, pt(t0, r_rr(t0, sb)), pt(t1, r_rr(t1, sb)), z, z + 0.45, scale(seat_lo, 1.3), ctr)
        c0, c1 = pt(t0, r_rr(t0, LB1)), pt(t1, r_rr(t1, LB1))
        vwall(K, c0, c1, F + 3.2 if vom else F, F + 6.0, lin('#c9c9cc'), pt(tm, 200))  # back of the bowl from the concourse
        vwall(K, c0, c1, F + 5.9, F + 7.0, lin('#151515') if i % 4 else lin('#7a3fb5'), ctr, NEON)  # LED ribbon fascia
        if vom:  # tunnel ceiling and side walls
            q(r_rr(t0, LB0), r_rr(t1, LB0), r_rr(t0, LB1), r_rr(t1, LB1), F + 3.2, lin('#6a6a6e'), False)
        else:
            Rm.wall(pt(t0, r_rr(t0, LB0)), pt(t1, r_rr(t1, LB0)), 4.0, 0.6, 0, out=pt(tm, r_rr(tm, LB0) + 3))
            Rm.wall(c0, c1, 4.0, 0.6, 0, out=pt(tm, r_rr(tm, LB1) - 3))
        # upper bowl: 0.9 m rows from the fascia up to the wall (as many as fit), suite windows above
        ui0, ui1 = r_rr(t0, LB1 + 0.4), r_rr(t1, LB1 + 0.4)
        n = max(0, min(int((ro0 - 0.6 - ui0) / 0.9), int((ro1 - 0.6 - ui1) / 0.9), 26))
        if rot:
            n = min(n, 6)
        for j in range(n):
            z = up_h(j)
            q(ui0 + j * 0.9, ui1 + j * 0.9, ui0 + (j + 1) * 0.9, ui1 + (j + 1) * 0.9, z, seat_up if j % 2 == 0 else scale(seat_up, 0.85))
            vwall(K, pt(t0, ui0 + j * 0.9), pt(t1, ui1 + j * 0.9), up_h(j - 1) if j else F + 6.0, z, riser, ctr)
        ztop = up_h(n - 1) if n else F + 6.0
        if rot:
            q(ui0 + n * 0.9, ui1 + n * 0.9, ro0, ro1, ztop, lin('#4a4a4e'))
            vwall(K, pt(t0, ui0 + n * 0.9), pt(t1, ui1 + n * 0.9), ztop, F + 22, char, ctr)
        else:
            q(ui0 + n * 0.9, ui1 + n * 0.9, ro0, ro1, ztop, lin('#4a4a4e'))
            if ztop + 3.5 < F + 21:  # suites round the top
                vwall(K, pt(t0, ro0 - 0.05), pt(t1, ro1 - 0.05), ztop + 1.0, ztop + 3.0, lin('#ffe6b0') if i % 2 else lin('#d8e4ec'), ctr, LIT)
    # the rink: ice, lines, circles, goals and creases, benches
