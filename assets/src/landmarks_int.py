            vwall(K, b0, b1, F + 0.25, F + 1.07, board, ctr)
            vwall(K, o0, o1, F, F + 1.07, board, pt(tm, 200))
            flat(K, [b0, b1, o1, o0], F + 1.07, lin('#e2e2e2'))
            Rm.wall(b0, b1, 1.1, 0.3)
