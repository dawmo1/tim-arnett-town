# Quad Cities interiors (roadmap 5), loaded at the end of landmarks.py (same globals: Kit, finish, lin, B, ...).
# Walk-in interiors for the Moline / Rock Island / Arsenal / airport / NorthPark / Black Hawk landmarks: <name>_int.glb
# at the exterior's anchor (src/landmarks.js puts it on the same ground height). Besides the GLB, each builder writes
# its collision walls, the townspeople standing in it and the counters you can use (E) to src/landmark-rooms.js, so the
# geometry and the game data never drift apart. References: docs/landmarks-references.md (Interiors, roadmap 5).
import json as _json


class Rooms:
    """collects game data for one interior: walls (Blender segments -> game solid boxes), crowd, spots"""

    def __init__(self, anchor):
        self.ax, self.az = anchor
        self.solid, self.crowd, self.spots, self.halls = [], [], [], []

    def g(self, p):
        return (p[0] + self.ax, self.az - p[1])

    def wall(self, a, b, h, th=0.8, up=0.0, out=None):
        """a wall box along Blender segment a->b, h tall from `up` above the floor; out: a Blender point on the side
        the box is pushed to (so its inner face sits on the segment); without it the box is centred on the segment"""
        A, Bq = self.g(a), self.g(b)
        dx, dz = Bq[0] - A[0], Bq[1] - A[1]
        Ln = math.hypot(dx, dz)
        if Ln < 0.05:
            return
        cx, cz = (A[0] + Bq[0]) / 2, (A[1] + Bq[1]) / 2
        if out is not None:
            O = self.g(out)
            nx, nz = -dz / Ln, dx / Ln
            if (O[0] - cx) * nx + (O[1] - cz) * nz < 0:
                nx, nz = -nx, -nz
            cx, cz = cx + nx * th / 2, cz + nz * th / 2
        self.solid.append([round(cx, 2), round(cz, 2), round(Ln / 2 + 0.05, 2), round(th / 2, 2), round(h, 2), round(up, 2), round(math.atan2(-dz, dx), 4)])

    def block(self, x0, x1, y0, y1, h, up=0.0):
        """an axis-aligned Blender box as a solid"""
        A, Bq = self.g((x0, y0)), self.g((x1, y1))
        self.solid.append([round((A[0] + Bq[0]) / 2, 2), round((A[1] + Bq[1]) / 2, 2), round(abs(x1 - x0) / 2, 2), round(abs(y1 - y0) / 2, 2), round(h, 2), round(up, 2), 0])

    def person(self, p, face, pose, up=0.0, role='walk'):
        """someone at Blender point p looking at Blender point `face` (or with game heading `face`, radians)"""
        x, z = self.g(p)
        if isinstance(face, (tuple, list)):
            fx, fz = self.g(face)
            h = math.atan2(fx - x, fz - z)
        else:
            h = face
        self.crowd.append([round(x, 2), round(z, 2), round(h, 3), pose, round(up, 2), role])

    def hall(self, name, c, w, d, axis=(1.0, 0.0), up=0.02, ly=4.0, light=None):
        """a room for interiors.js: centre c and its own x axis `axis`, both in Blender coords; w along the axis"""
        x, z = self.g(c)
        h = dict(name=name, x=round(x, 2), z=round(z, 2), w=round(w, 2), d=round(d, 2), rot=round(math.atan2(axis[1], axis[0]), 4), up=up, ly=ly)
        if light:
            h['light'] = light
        self.halls.append(h)

    def spot(self, p, r, act, title, menu=None):
        x, z = self.g(p)
        self.spots.append([round(x, 2), round(z, 2), r, act, title] + ([menu] if menu else []))

    def save(self, name):
        p = ROOT + 'src/landmark-rooms.js'
        J = {}
        if os.path.exists(p):
            J = _json.loads(open(p).read().split('export const ROOMS = ', 1)[1].rstrip().rstrip(';'))
        J[name] = dict(solid=self.solid, crowd=self.crowd, spots=self.spots, halls=self.halls)
        head = ('// Generated by assets/src/landmarks_int.py (the roadmap-5 *_int builders): rebuild the interior instead of editing.\n'
                '// Per interior: solid walls [x, z, half x, half z, height, base above the ground at the anchor, heading], the crowd\n'
                '// [x, z, heading, pose, floor height, role] and counters [x, z, radius, act, title, menu] (venues.js).\n'
                'export const ROOMS = ')
        body = ',\n'.join('  %s: %s' % (_json.dumps(k), _json.dumps(v, separators=(',', ':'))) for k, v in sorted(J.items()))
        open(p, 'w').write(head + '{\n' + body + '\n};\n')
        return len(self.solid)


def rr_sdf(px, py, a, b, r):
    qx, qy = abs(px) - (a - r), abs(py) - (b - r)
    return math.hypot(max(qx, 0), max(qy, 0)) + min(max(qx, qy), 0) - r


def rr_ray(th, a, b, r, t):
    """distance from the centre along angle th to the outline of the rounded rect (half a x b, corner r) grown by t"""
    lo, hi = 0.0, a + b + abs(t) + 10
    c, s = math.cos(th), math.sin(th)
    for _ in range(40):
        m = (lo + hi) / 2
        if rr_sdf(c * m, s * m, a, b, r) < t:
            lo = m
        else:
            hi = m
    return lo


def poly_ray(P, cx, cy, th):
    """distance from (cx, cy) along angle th to the nearest edge of polygon P"""
    dx, dy = math.cos(th), math.sin(th)
    best = 1e9
    for i in range(len(P)):
        (x1, y1), (x2, y2) = P[i], P[(i + 1) % len(P)]
        ex, ey = x2 - x1, y2 - y1
        den = dx * ey - dy * ex
        if abs(den) < 1e-9:
            continue
        t = ((x1 - cx) * ey - (y1 - cy) * ex) / den
        u = ((x1 - cx) * dy - (y1 - cy) * dx) / den
        if t > 0 and -1e-6 <= u <= 1 + 1e-6:
            best = min(best, t)
    return best


def in_poly(P, x, y):
    ins = False
    j = len(P) - 1
    for i in range(len(P)):
        if (P[i][1] > y) != (P[j][1] > y) and x < (P[j][0] - P[i][0]) * (y - P[i][1]) / (P[j][1] - P[i][1]) + P[i][0]:
            ins = not ins
        j = i
    return ins


def flat(K, pts, z, col, m=BODY, up=True):
    """a horizontal polygon at height z seen from above (up) or from below"""
    pts = [(p[0], p[1], z) for p in pts]
    a = sum((pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]) for i in range(len(pts)))
    if (a > 0) != up:
        pts = pts[::-1]
    K.face(pts, col, m)


def frect(K, x0, x1, y0, y1, z, col, m=BODY, up=True):
    flat(K, [(x0, y0), (x1, y0), (x1, y1), (x0, y1)], z, col, m, up)


def disc(K, cx, cy, r, z, col, m=BODY, seg=24, up=True, r0=0.0):
    """a flat disc (or a ring from r0) at height z"""
    if r0 > 0:
        for i in range(seg):
            a0, a1 = 2 * math.pi * i / seg, 2 * math.pi * (i + 1) / seg
            flat(K, [(cx + math.cos(a0) * r0, cy + math.sin(a0) * r0), (cx + math.cos(a1) * r0, cy + math.sin(a1) * r0), (cx + math.cos(a1) * r, cy + math.sin(a1) * r), (cx + math.cos(a0) * r, cy + math.sin(a0) * r)], z, col, m, up)
    else:
        flat(K, [(cx + math.cos(2 * math.pi * i / seg) * r, cy + math.sin(2 * math.pi * i / seg) * r) for i in range(seg)], z, col, m, up)


def vwall(K, a, b, z0, z1, col, toward, m=BODY):
    """vertical quad on segment a-b facing the point `toward`"""
    iface(K, [(a[0], a[1], z0), (b[0], b[1], z0), (b[0], b[1], z1), (a[0], a[1], z1)], (toward[0], toward[1], (z0 + z1) / 2), col, m)


def wframe(a, b, toward, z=0.0):
    """frame on the wall a-b seen from `toward`: d points at the viewer, h up from z, u along the wall running so that
    u x up = d (quads and letters then face the viewer; the ends may swap, so callers use it symmetrically)"""
    if (toward[0] - a[0]) * (b[1] - a[1]) - (toward[1] - a[1]) * (b[0] - a[0]) < 0:
        a, b = b, a
    dx, dy = b[0] - a[0], b[1] - a[1]
    Ln = math.hypot(dx, dy)
    ux, uy = dx / Ln, dy / Ln
    nx, ny = uy, -ux
    return (lambda u, h, d: (a[0] + ux * u + nx * d, a[1] + uy * u + ny * d, z + h)), Ln


def wtext(K, a, b, toward, s, u, h, size, col, m=BODY, d=0.03, z=0.0):
    """flat letters on a wall a-b, readable from the `toward` side, centred u along it"""
    L, Ln = wframe(a, b, toward, z)
    return K.text(s, L, u, h, d, size, col, m, 0.03, res=1, front=True)


def counter(K, Rm, a, b, z, depth, col, top, toward, h=1.05):
    """a service counter along a-b reaching `depth` away from `toward`, with its collision; returns its frame"""
    L, Ln = wframe(a, b, toward, z)
    F_ = lambda u, hh, d: L(u, hh, -d)
    K.obox(F_, 0, Ln, 0, h, 0, depth, col, BODY, ('h-',))
    K.obox(F_, -0.05, Ln + 0.05, h, h + 0.06, -0.08, depth, top, BODY, ('h-',))
    Rm.wall(F_(0, 0, depth / 2)[:2], F_(Ln, 0, depth / 2)[:2], 1.2, depth + 0.1)
    return F_


def bench(K, Rm, x, y, along_x, n=4, col=lin('#2f3a45'), z=0.0, solid=True):
    """a row of n connected seats (gate seating, waiting areas): 0.55 m a seat"""
    L = n * 0.55
    if along_x:
        K.box(x - L / 2, x + L / 2, y - 0.25, y + 0.25, z + 0.38, z + 0.46, col)
        K.box(x - L / 2, x + L / 2, y + 0.2, y + 0.27, z + 0.46, z + 0.9, col)
        K.box(x - L / 2, x + L / 2, y - 0.05, y + 0.05, z, z + 0.38, lin('#9aa0a6'))
        if solid:
            Rm.block(x - L / 2, x + L / 2, y - 0.3, y + 0.3, 0.9)
    else:
        K.box(x - 0.25, x + 0.25, y - L / 2, y + L / 2, z + 0.38, z + 0.46, col)
        K.box(x + 0.2, x + 0.27, y - L / 2, y + L / 2, z + 0.46, z + 0.9, col)
        K.box(x - 0.05, x + 0.05, y - L / 2, y + L / 2, z, z + 0.38, lin('#9aa0a6'))
        if solid:
            Rm.block(x - 0.3, x + 0.3, y - L / 2, y + L / 2, 0.9)


def plant(K, x, y, z=0.0, r=0.5, h=1.8):
    K.cyl(x, y, r, z, z + 0.6, lin('#8a8478'), BODY, 8)
    K.cyl(x, y, r * 1.3, z + 0.6, z + h, lin('#3f7a3a'), BODY, 6, r1=0.15)


def door_gap(L, Ln, c, half):
    """(u0, u1) of a door centred on Blender point c if it lies on the wall frame L (else None)"""
    o = Vector(L(0, 0, 0))
    ux = Vector(L(1, 0, 0)) - o
    v = Vector((c[0], c[1], o.z)) - o
    s = v.dot(ux)
    if half < s < Ln - half and (v - ux * s).length < 1.0:
        return (s - half, s + half)
    return None


def int_done(name, K, Rm, anchor, cam, target, render, lens=18):
    """finish an interior: GLB, game data, a preview from inside"""
    o = K.obj(name + '_int')
    res = finish(name + '_int', [o], anchor)
    res['walls'] = Rm.save(name)
    res['people'] = len(Rm.crowd)
    if render:
        res['png'] = [inside_shot(name + '_int', cam, target, lens)]
    return res


